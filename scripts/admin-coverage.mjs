#!/usr/bin/env node
// Catalog drift check: every guarded admin controller must have an intentional home.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { createRequire } from 'node:module';
import { adminCapabilities } from '../tools/mcp/src/admin-catalog.mjs';
const ts = createRequire(import.meta.url)('typescript');
const root = resolve(import.meta.dirname, '..');
const homes = {
  'admin-affiliate': 'affiliates', 'admin-analytics': 'analytics',
  'admin-announcements': 'announcements', 'admin-assistant': 'assistant',
  'admin-billing': 'users', 'admin-crews': 'crews', 'admin-daily-content': 'jobs',
  'admin-email-samples': 'site-settings', 'admin-feedback': 'feedback',
  'admin-image-review': 'media-review', 'admin-impersonation': 'impersonate',
  'admin-intro-brief': 'intros', 'admin-jobs': 'jobs', 'admin-newsletters': 'newsletters',
  'admin-operations': 'assistant', 'admin-pages': 'users', 'admin-push': 'push',
  'admin-referral': 'affiliates', 'admin-reports': 'reports', 'admin-search': 'search',
  'admin-site-config': 'site-settings', 'admin-users': 'users',
  'admin-verification': 'verification', marvin: 'marv', taxonomy: 'jobs', health: 'diagnostics', metrics: 'analytics',
};
function files(dir) { return readdirSync(dir, { withFileTypes: true }).flatMap(entry => entry.isDirectory() ? files(join(dir, entry.name)) : [join(dir, entry.name)]); }
const decorators = node => (ts.getDecorators(node) ?? []).map(d => d.expression);
const named = (list, name) => list.find(d => ts.isCallExpression(d) && d.expression.getText() === name);
const guarded = list => list.some(d => ts.isCallExpression(d) && d.expression.getText() === 'UseGuards' && d.arguments.some(arg => arg.getText() === 'AdminGuard'));
const literal = node => node && ts.isStringLiteralLike(node) ? node.text : '';
const rows = [];
for (const file of files(join(root, 'src/modules')).filter(path => path.endsWith('.controller.ts'))) {
  const source = ts.createSourceFile(file, readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
  for (const cls of source.statements.filter(ts.isClassDeclaration)) {
    const classDecorators = decorators(cls);
    const controller = named(classDecorators, 'Controller');
    if (!controller) continue;
    for (const member of cls.members.filter(ts.isMethodDeclaration)) {
      const methodDecorators = decorators(member);
      if (!guarded(classDecorators) && !guarded(methodDecorators)) continue;
      const route = methodDecorators.find(d => ts.isCallExpression(d) && ['Get', 'Post', 'Patch', 'Put', 'Delete'].includes(d.expression.getText()));
      if (!route) continue;
      const key = file.split('/').at(-1).replace('.controller.ts', '');
      const methodHome = key === 'admin-operations' && ['attention', 'activation'].includes(literal(route.arguments[0])) ? literal(route.arguments[0]) : null;
      const home = methodHome ?? homes[key];
      if (!home || !adminCapabilities.some(cap => cap.id === home)) throw new Error(`Account for ${key} in the shared catalog before shipping it.`);
      const path = [literal(controller.arguments[0]), literal(route.arguments[0])].filter(Boolean).join('/');
      rows.push({ method: route.expression.getText().toUpperCase(), path: `/v1/${path}`, home, file: file.slice(root.length + 1), line: source.getLineAndCharacterOfPosition(member.getStart()).line + 1 });
    }
  }
}
rows.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
const output = '# Admin endpoint inventory\n\nGenerated by `node scripts/admin-coverage.mjs`. Every route below is gated by `AdminGuard`.\nThe companion [experience review](admin-experience.md) records assistant actions, manual controls, and platform gaps.\n\n' +
  `${rows.length} guarded routes, ${adminCapabilities.length} catalog entries.\n\n| Route | Catalog home | Implementation |\n| --- | --- | --- |\n` +
  rows.map(row => `| ${row.method} ${row.path} | ${row.home} | [source](../${row.file}#L${row.line}) |`).join('\n') + '\n';
const target = join(root, 'docs/admin-endpoints.md');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Admin endpoint inventory drifted. Run node scripts/admin-coverage.mjs.');
} else writeFileSync(target, output);
console.log(`Accounted for ${rows.length} guarded admin endpoints.`);
